export const WORKFLOW_STEP_META: { id: string; label: string; detail: string }[] = [
  { id: 'application', label: 'Customer Application', detail: 'Application submitted with requested account type and expected usage.' },
  { id: 'documents', label: 'Identity Documents', detail: 'PAN, Aadhaar, address proof and photograph collected.' },
  { id: 'extraction', label: 'AI Document Extraction', detail: 'OCR and field extraction run across all submitted documents.' },
  { id: 'verification', label: 'Document Verification', detail: 'Extracted fields checked against document authenticity signals.' },
  { id: 'consistency', label: 'Identity Consistency Check', detail: 'Name, date of birth and address cross-checked across documents.' },
  { id: 'risk', label: 'Risk Screening', detail: 'Application screened against simulated risk and fraud signals.' },
  { id: 'decision', label: 'AI Decision', detail: 'AI recommends automated approval or routes the case to a human reviewer.' },
  { id: 'account', label: 'Account Setup', detail: 'Core banking account provisioned in the sandbox ledger.' },
  { id: 'activation', label: 'Digital Banking Activation', detail: 'Mobile and net banking access activated for the customer.' },
];

export function buildWorkflow(statuses: WorkflowStepStatus[]): WorkflowStep[] {
  return WORKFLOW_STEP_META.map((meta, index) => ({ ...meta, status: statuses[index] ?? 'Pending' }));
}

export function initials(name: string) {
  return name.split(' ').map((part) => part[0]).join('').slice(0, 2).toUpperCase();
}

function makeDoc(partial: Partial<OnboardingDocument> & { type: OnboardingDocument['type']; status: DocumentStatus }): OnboardingDocument {
  return { fileLabel: `${partial.type.toLowerCase().replace(' ', '-')}-scan.jpg`, ...partial };
}

