export function buildReviewQueue(source: OnboardingApplication[]): ReviewCase[] {
  return source
    .filter((application) => application.kycStatus === 'Human Review')
    .map((application) => {
      const flaggedDoc = application.documents.find((document) => document.flag);
      return {
        applicationId: application.id,
        customerName: application.customerName,
        issue: flaggedDoc?.flag?.issue ?? 'Requires manual review',
        aiConfidence: application.aiConfidence,
        priority: application.risk === 'High' ? 'High' : application.risk === 'Medium' ? 'Medium' : 'Low',
        waiting: application.submitted,
        status: 'Awaiting review' as const,
      };
    });
}

export function newAuditEvent(agent: string, event: string): AuditEvent {
  return { time: new Date().toLocaleTimeString('en-IN', { hour12: false }), agent, event };
}
